// Proves the step 1 workflow from the command line and writes a Markdown report.
//   node --env-file-if-exists=.env scripts/demo.js [outDir] [videoA videoB]
// Without video paths it generates two synthetic test videos that we create (and so own).
import fs from "node:fs/promises";
import path from "node:path";
import { createProvider, discover } from "../src/discovery/index.js";
import { createOriginalBrief } from "../src/original.js";
import { makeCuts } from "../src/clip/index.js";
import { probe } from "../src/clip/ffmpeg.js";
import { fmt } from "../src/discovery/ranking.js";
import { sha256File } from "../src/rights.js";
import { makeTestMedia } from "./make-test-media.js";

const outDir = path.resolve(process.argv[2] || "data/demo");
await fs.mkdir(outDir, { recursive: true });
const provider = createProvider();
const lines = [`# ClipCut Studio step 1 demo`, ``, `Run: ${new Date().toISOString()}`, `Search source: **${provider.source}**${provider.source === "sample" ? " (synthetic data, no YouTube API key configured)" : ""}`, ``];

for (const q of ["football", "cooking", "luxury villas"]) {
  for (const mode of ["breakout", "views"]) {
    const r = await discover(provider, { q, mode, period: "30d" });
    lines.push(`## "${q}" · ${mode === "breakout" ? "Breaking out now" : "Most viewed"}`, ``, `| # | Title | Channel | Views | Views/h | vs channel | Why |`, `|---|---|---|---|---|---|---|`);
    for (const v of r.results.slice(0, 5)) {
      const o = v.metrics.outlierScore;
      lines.push(`| ${v.rank} | ${v.url ? `[${v.title}](${v.url})` : v.title} | ${v.channelTitle} | ${fmt(v.views)} | ${fmt(v.metrics.viewsPerHour.value)} | ${o.value ?? "n/a"}x (${o.basis}) | ${v.reasons.slice(0, 2).join("; ")} |`);
    }
    lines.push(``);
  }
}

const top = (await discover(provider, { q: "luxury villas" })).results[0];
const brief = createOriginalBrief(top, { topic: "luxury villas" });
lines.push(`## Original version brief (for "${top.title}")`, ``, `Format: ${brief.format}, ${brief.targetSeconds}s, ${brief.orientation}`, ``, ...brief.hooks.map((h, i) => `${i + 1}. ${h}`), ``);

const given = process.argv.slice(3, 5);
const files = given.length === 2 ? given.map((f) => path.resolve(f)) : await makeTestMedia(path.join(outDir, "sources"));
const sources = files.map((f, i) => ({ id: `source-${"AB"[i]}`, label: path.basename(f), file: f }));
lines.push(`## Clip from two source files`, ``);
for (const s of sources) {
  const info = await probe(s.file);
  lines.push(`- ${s.label}: ${info.duration.toFixed(1)}s, ${info.width}×${info.height}, sha256 ${(await sha256File(s.file)).slice(0, 16)}…, rights: ${given.length ? "supplied by the user" : "generated by this script, so owned outright"}`);
}
const t0 = Date.now();
const { cuts, analysis } = await makeCuts(sources, outDir, { targetSeconds: 30, aspect: "vertical" });
lines.push(``, `Dead air removed: ${analysis.map((a) => `${a.sourceId} ${a.deadAirSeconds}s`).join(", ")}. Render time ${((Date.now() - t0) / 1000).toFixed(1)}s.`, ``, `| Cut | Opening | Length | Size | Codecs | Shots | File |`, `|---|---|---|---|---|---|---|`);
for (const c of cuts) lines.push(`| ${c.id} ${c.name} | ${c.opening} | ${c.media.duration}s | ${c.media.width}×${c.media.height} | ${c.media.videoCodec}/${c.media.audioCodec} | ${c.segments.map((s) => `${s.sourceId} ${s.start}-${s.end}`).join(", ")} | ${c.file} |`);
await fs.writeFile(path.join(outDir, "report.md"), lines.join("\n") + "\n");
await fs.writeFile(path.join(outDir, "cuts.json"), JSON.stringify({ cuts, analysis }, null, 2));
console.log(`Report: ${path.join(outDir, "report.md")}`);
